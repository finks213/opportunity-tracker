test("§22 — desktop figures in the report match the desktop JSON exactly", () => {
  if (!existsSync(join(ROOT, "audit", "desktop-measurements.json"))) {
    assert.fail("audit/desktop-measurements.json is required evidence");
  }
  const d = readJson("audit/desktop-measurements.json");
  assert.ok(REPORT.includes(d.browser.version), "the report must print the measured browser version");
  assert.ok(REPORT.includes(String(d.normalMode.frameCount)));
  assert.ok(REPORT.includes(String(d.renderStressMode.frameCount)));
  assert.ok(REPORT.includes(d.normalMode.medianFrameTimeMs.toFixed(2)));
  assert.ok(REPORT.includes(d.renderStressMode.p95FrameTimeMs.toFixed(2)));
  assert.ok(REPORT.includes(String(d.normalMode.populationAfterAdvance)));

  // Generation semantics must be stated, and consistent.
  assert.match(
    REPORT,
    new RegExp(`\\*\\*${d.generationSemantics.finalStateGeneration}\\*\\* with \\*\\*${d.normalMode.populationAfterAdvance}\\*\\* living`),
    "the report must tie the population to an explicit final generation"
  );
  // The ambiguous revision-3 field name must not be a live key anywhere. The
  // report is allowed to NAME it while explaining the defect — that mention is
  // the record — so the rule is about use, not about the English text.
  const deskText = read("audit/desktop-measurements.json");
  assert.ok(
    !deskText.includes("populationAfter180Generations"),
    "the ambiguous field name must not appear in the raw desktop evidence"
  );
  const reportLines = REPORT.split("\n");
  for (let i = 0; i < reportLines.length; i++) {
    if (!reportLines[i].includes("populationAfter180Generations")) continue;
    // Judge the surrounding context, not the single line: a withdrawal can put the
    // marker in its section heading or the following sentence.
    const context = reportLines.slice(Math.max(0, i - 6), i + 4).join(" ");
    assert.match(
      context,
      /[Rr]evision[- ]3|ambiguity|retired|[Ww]ithdrawn/,
      `the report mentions populationAfter180Generations without marking it as the revision-3 name:\n  ${reportLines[i].trim()}`
    );
  }

  // Memory: the report must not publish an unverified browser delta as evidence.
  const mem = d.memoryAcrossAdvance;
  assert.ok(REPORT.includes("`node:process.memoryUsage()`"), "the authoritative channel must be named");
  if (!mem.browser.usable) {
    assert.ok(
      REPORT.includes("**The browser heap figure is withdrawn as evidence.**"),
      "an unusable browser memory channel must be withdrawn in the report, not quietly printed"
    );
    // The old style of claim must be gone.
    assert.ok(
      !/Memory across a 180-generation run: [\d,]+ → [\d,]+ bytes/.test(REPORT),
      "the report must not present a browser heap delta as the memory-growth result"
    );
  }
  // The desktop run must not be presented as satisfying the iPad gate.
  assert.equal(d.windowComparison.satisfiesIpadGateWindows, false);
  assert.ok(REPORT.includes("Satisfies the iPad gate's windows: false"));
  assert.ok(REPORT.includes("PENDING_HUMAN_DEVICE_TEST"));
});

