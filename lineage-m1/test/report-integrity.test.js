test("§20 — the report's suite counts equal the raw TAP summary", () => {
  assert.ok(TAP.tests !== null, "the raw TAP summary must be parseable");
  assert.ok(TAP.pass !== null && TAP.fail !== null);

  // Every count must appear in the report...
  for (const [label, value] of [["tests", TAP.tests], ["pass", TAP.pass], ["fail", TAP.fail]]) {
    assert.match(
      REPORT,
      new RegExp(`\\| ${label} \\| ${value} \\|`),
      `the report must print the raw ${label} count ${value}`
    );
  }
  // ...and the gate-table summary must state the SAME outcome, in whichever form
  // applies. A green run reads "N/N, 0 failures"; a failing run must say FAIL with
  // the real numbers rather than quietly printing a pass shape.
  if (TAP.fail === 0) {
    const green = [...REPORT.matchAll(/(\d+)\s*\/\s*(\d+), 0 failures/g)].map((m) => [Number(m[1]), Number(m[2])]);
    assert.ok(green.length > 0, "a green run must state the pass/total summary");
    for (const [p, t] of green) {
      assert.equal(t, TAP.tests, `the report claims ${t} tests but the runner reported ${TAP.tests}`);
      assert.equal(p, TAP.pass, `the report claims ${p} passing but the runner reported ${TAP.pass}`);
    }
    assert.ok(
      !/\*\*FAIL\*\* — \d+ of \d+ failing/.test(REPORT),
      "a green run must not print a failing summary"
    );
  } else {
    const red = [...REPORT.matchAll(/\*\*FAIL\*\* — (\d+) of (\d+) failing/g)].map((m) => [Number(m[1]), Number(m[2])]);
    assert.ok(red.length > 0, "a failing run must be reported as FAIL, not hidden");
    for (const [f, t] of red) {
      assert.equal(f, TAP.fail, `the report claims ${f} failures but the runner reported ${TAP.fail}`);
      assert.equal(t, TAP.tests, `the report claims ${t} tests but the runner reported ${TAP.tests}`);
    }
  }

  // Wall-clock duration must NOT be reproduced: it differs on every run, so
  // printing it would make this comparison unsatisfiable by construction.
  assert.ok(
    !/^\| duration \|/m.test(REPORT),
    "the report must not print the run duration — it is nondeterministic and would " +
    "make the report and the results file permanently disagree"
  );
  // No stale count from an earlier revision may be ASSERTED. Quoting one inside an
  // explicit withdrawal is required, not forbidden — §9b names the revision-3
  // "119 tests … 119/119" claim precisely so a reader cannot carry it forward.
  for (const stale of [119, 122, 148, 172]) {
    if (stale === TAP.tests) continue;
    const pattern = new RegExp(`${stale}\\s*/\\s*${stale}`);
    const lines = REPORT.split("\n");
    for (let i = 0; i < lines.length; i++) {
      if (!pattern.test(lines[i])) continue;
      const context = lines.slice(Math.max(0, i - 6), i + 4).join(" ");
      assert.match(
        context,
        /[Ww]ithdrawn|[Rr]evision[- ][123]|stale|retired/,
        `the report asserts the stale suite count ${stale}/${stale} outside a withdrawal:\n  ${lines[i].trim()}`
      );
    }
  }
});

test("§9/§18 — modelDefinitionHash is the principal identity and the subset hash is labelled nonauthoritative", () => {
  assert.ok(
    REPORT.includes(`\`${HASH_LABELS.authoritative}\`** (authoritative)`),
    "the complete-model hash must be presented as authoritative"
  );
  assert.ok(
    REPORT.includes(`\`${HASH_LABELS.nonauthoritative}\` (**NONAUTHORITATIVE**)`),
    "the tuning-only subset hash must be explicitly labelled nonauthoritative"
  );
  assert.ok(REPORT.includes(CHAR.modelDefinitionHash), "the authoritative hash value must be printed");
  assert.ok(REPORT.includes(CHAR.tuningConfigHash), "the subset hash value must be printed, labelled");

  // The subset hash must never be presented as "the" config hash again.
  assert.ok(
    !/^\s*[-|]\s*Config hash:/m.test(REPORT),
    'no line may publish a bare "Config hash:" — the report distinguishes the two hashes'
  );
  // Exactly one build-identity block. Revision 3 had two.
  const identityBlocks = [...REPORT.matchAll(/### Build identity/g)].length;
  assert.equal(identityBlocks, 1, "the report must contain exactly one build-identity block");
  const configLines = [...REPORT.matchAll(/^\| Configuration \| /gm)].length;
  assert.equal(configLines, 1, "the configuration must be stated exactly once");

  // Evidence files must agree with each other on both hashes.
  assert.equal(FIXTURE.modelDefinitionHash, CHAR.modelDefinitionHash, "evidence files disagree on the model hash");
  assert.equal(FIXTURE.tuningConfigHash, CHAR.tuningConfigHash, "evidence files disagree on the subset hash");
  assert.notEqual(CHAR.modelDefinitionHash, CHAR.tuningConfigHash, "the two hashes must be distinguishable");
});

