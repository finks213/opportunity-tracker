/**
 * FINAL_REPORT.md must agree with the raw evidence it claims to summarize
 * (contract §26 status artifacts, §27 audit evidence, §28 completion law).
 *
 * Revision-4 repair. Revisions 1-3 hand-maintained the report and it drifted.
 * Reproduced against the revision-3 bundle:
 *
 *   $ grep -n "Config hash" FINAL_REPORT.md
 *   54:- Config hash: `edb81695973b81ab8f87f7ef9dde9d8c5b3d4c7dfbeb45f385547edd86ee86de`
 *
 *     A DUPLICATED build-identity block (lines 51-57 repeated lines 35-38) that
 *     published `edb81695…` as "Config hash", while line 141 of the SAME report
 *     labelled that hash "the tuning config only" and named
 *     `modelDefinitionHash` as the complete one. The report contradicted itself
 *     about which hash identifies the model.
 *
 *   $ grep -o "119 tests" FINAL_REPORT.md | head -1 ; grep "^# tests" audit/test-results.txt
 *   119 tests
 *   # tests 172
 *
 *     The gate table claimed "119 tests … 119/119" while the raw TAP summary in
 *     the same bundle reported 172.
 *
 *   $ grep -n "Memory across a 180-generation run" -A1 FINAL_REPORT.md
 *     A browser `performance.memory` delta published as memory-growth evidence,
 *     from a channel that was never probed for resolution.
 *
 * The report is now GENERATED by `tools/writeFinalReport.mjs`. These tests make
 * drift a build failure: every assertion compares the committed report against
 * the raw evidence, and several re-derive the number independently rather than
 * trusting either file.
 */

